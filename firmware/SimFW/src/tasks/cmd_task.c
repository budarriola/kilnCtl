typedef void (*cmd_handler_fn)(const uint8_t *args, uint8_t args_len, uint8_t *out, uint8_t *out_len,
                                uint8_t out_cap);

static void handle_sys_ping(const uint8_t *args, uint8_t args_len, uint8_t *out, uint8_t *out_len, uint8_t out_cap)
{
    (void)args;
    (void)args_len;
    reply_writer_t w;
    rw_init(&w, out, out_cap);
    rw_u8(&w, SIMFW_CMD_STATUS_OK);
    *out_len = w.len;
}

// Shared by GET_VERSION and GET_CAPS -- both start with the same
// version/build-identity block (protocol version + min compatible, this
// firmware's major.minor.patch, dirty flag, git hash) per docs/PROTOCOL.md;
// GET_CAPS appends the capability fields afterward. Factored out so the two
// wire layouts cannot drift apart on this shared prefix.
static void write_version_block(reply_writer_t *w)
{
    rw_u16le(w, (uint16_t)BENCHPROTO_PROTOCOL_VERSION);
    rw_u16le(w, (uint16_t)BENCHPROTO_MIN_COMPATIBLE);
    rw_u8(w, SIMFW_FW_VERSION_MAJOR);
    rw_u8(w, SIMFW_FW_VERSION_MINOR);
    rw_u8(w, SIMFW_FW_VERSION_PATCH);
    rw_u8(w, (uint8_t)SIMFW_FW_GIT_DIRTY);

    size_t hlen = strlen(SIMFW_FW_GIT_COMMIT);
    if (hlen > 255u) {
        hlen = 255u; // can't happen for a real short git hash ("unknown" or ~7-12 hex chars); defensive only
    }
    rw_u8(w, (uint8_t)hlen);
    rw_bytes(w, (const uint8_t *)SIMFW_FW_GIT_COMMIT, (uint8_t)hlen);
}

static void handle_sys_get_version(const uint8_t *args, uint8_t args_len, uint8_t *out, uint8_t *out_len,
                                    uint8_t out_cap)
{
    (void)args;
    (void)args_len;
    reply_writer_t w;
    rw_init(&w, out, out_cap);
    rw_u8(&w, SIMFW_CMD_STATUS_OK);
    write_version_block(&w);
    *out_len = w.len;
}

static void handle_sys_get_caps(const uint8_t *args, uint8_t args_len, uint8_t *out, uint8_t *out_len,
                                 uint8_t out_cap)
{
    (void)args;
    (void)args_len;
    reply_writer_t w;
    rw_init(&w, out, out_cap);
    rw_u8(&w, SIMFW_CMD_STATUS_OK);
    write_version_block(&w);
    rw_u8(&w, SIMFW_CAPS_ZONE_COUNT_MIN);
    rw_u8(&w, SIMFW_CAPS_ZONE_COUNT_MAX);
    rw_u8(&w, SIMFW_CAPS_ZONE_COUNT_DEFAULT);
    rw_u8(&w, SIMFW_CAPS_TC_MAIN_CHANNELS);
    rw_u8(&w, SIMFW_CAPS_TC_SAFETY_CHANNELS);
    rw_u8(&w, SIMFW_CAPS_CT_CHANNELS);
    rw_u8(&w, SIMFW_CAPS_RELAY_CHANNELS);
    rw_u32le(&w, SIMFW_CAPS_FEATURE_BITMASK);
    *out_len = w.len;
}

// request: {u8 keep_params} -- sim_engine_reset()'s own bool: true = keep
// the current zone params, reinit state from their T0; false = reload the
// last-selected preset first (DESIGN_NOTES.md 6.1's sim_reset tool doc). Queued,
// same as every other MODEL-group setter sim_engine.h documents (this
// function lives in that header's MODEL-group command surface even though
// it is exposed here under SYS, per DESIGN_NOTES.md sec 5's own command-group
// table) -- a false return means the internal command queue was full, not
// a bad argument.
static void handle_sys_reset_sim(const uint8_t *args, uint8_t args_len, uint8_t *out, uint8_t *out_len,
                                  uint8_t out_cap)
{
    arg_reader_t r;
    ar_init(&r, args, args_len);
    uint8_t keep_params = ar_u8(&r);

    reply_writer_t w;
    rw_init(&w, out, out_cap);
    if (r.overflow) {
        rw_u8(&w, SIMFW_CMD_STATUS_ERR_BAD_ARGS);
        *out_len = w.len;
        return;
    }
    rw_u8(&w, sim_engine_reset(keep_params != 0) ? SIMFW_CMD_STATUS_OK : SIMFW_CMD_STATUS_ERR_BUSY);
    *out_len = w.len;
}

