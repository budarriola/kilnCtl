// --- Reply payload builder ---------------------------------------------

// Bounds-checked little-endian appender for a reply payload
// (docs/PROTOCOL.md's "multi-byte fields inside command payloads are
// little-endian" convention, BENCHPROTO.md section 3). `overflow` latches
// once any append is refused, so a handler can fire a sequence of rw_*()
// calls without checking each return value individually and still end up
// with a short, safely-truncated payload rather than a buffer overrun --
// every handler below still finishes with *out_len = w.len, so a latched
// overflow is visible in the reply's own length field, not silently hidden.
typedef struct {
    uint8_t *buf;
    uint8_t cap;
    uint8_t len;
    bool overflow;
} reply_writer_t;

static void rw_init(reply_writer_t *w, uint8_t *buf, uint8_t cap)
{
    w->buf = buf;
    w->cap = cap;
    w->len = 0;
    w->overflow = false;
}

static void rw_bytes(reply_writer_t *w, const uint8_t *data, uint8_t n)
{
    if (w->overflow || (uint16_t)w->len + (uint16_t)n > (uint16_t)w->cap) {
        w->overflow = true;
        return;
    }
    memcpy(w->buf + w->len, data, n);
    w->len = (uint8_t)(w->len + n);
}

static void rw_u8(reply_writer_t *w, uint8_t v)
{
    rw_bytes(w, &v, 1);
}

static void rw_u16le(reply_writer_t *w, uint16_t v)
{
    uint8_t b[2] = {(uint8_t)(v & 0xFFu), (uint8_t)((v >> 8) & 0xFFu)};
    rw_bytes(w, b, 2);
}

static void rw_u32le(reply_writer_t *w, uint32_t v)
{
    uint8_t b[4] = {
        (uint8_t)(v & 0xFFu),
        (uint8_t)((v >> 8) & 0xFFu),
        (uint8_t)((v >> 16) & 0xFFu),
        (uint8_t)((v >> 24) & 0xFFu),
    };
    rw_bytes(w, b, 4);
}

static void rw_u64le(reply_writer_t *w, uint64_t v)
{
    uint8_t b[8];
    for (int i = 0; i < 8; i++) {
        b[i] = (uint8_t)((v >> (8 * i)) & 0xFFu);
    }
    rw_bytes(w, b, 8);
}

static void rw_f32le(reply_writer_t *w, float v)
{
    union {
        float f;
        uint32_t u;
    } conv;
    conv.f = v;
    rw_u32le(w, conv.u);
}

// --- Request payload reader ------------------------------------------------
// Mirror of reply_writer_t for the inbound args[]/args_len this file's
// handlers decode -- same bounds-checked, overflow-latching shape so a
// handler can pull a whole fixed-shape struct off the wire and check
// r.overflow exactly once at the end rather than after every field (docs/
// PROTOCOL.md's "multi-byte fields ... are little-endian" convention).
typedef struct {
    const uint8_t *buf;
    uint8_t len;
    uint8_t pos;
    bool overflow;
} arg_reader_t;

static void ar_init(arg_reader_t *r, const uint8_t *buf, uint8_t len)
{
    r->buf = buf;
    r->len = len;
    r->pos = 0;
    r->overflow = false;
}

static bool ar_bytes(arg_reader_t *r, uint8_t *out, uint8_t n)
{
    if (r->overflow || (uint16_t)r->pos + (uint16_t)n > (uint16_t)r->len) {
        r->overflow = true;
        if (out != NULL) {
            memset(out, 0, n);
        }
        return false;
    }
    memcpy(out, r->buf + r->pos, n);
    r->pos = (uint8_t)(r->pos + n);
    return true;
}

static uint8_t ar_u8(arg_reader_t *r)
{
    uint8_t v = 0;
    ar_bytes(r, &v, 1);
    return v;
}

static uint16_t ar_u16le(arg_reader_t *r)
{
    uint8_t b[2] = {0, 0};
    ar_bytes(r, b, 2);
    return (uint16_t)((uint16_t)b[0] | ((uint16_t)b[1] << 8));
}

static uint32_t ar_u32le(arg_reader_t *r)
{
    uint8_t b[4] = {0, 0, 0, 0};
    ar_bytes(r, b, 4);
    return (uint32_t)b[0] | ((uint32_t)b[1] << 8) | ((uint32_t)b[2] << 16) | ((uint32_t)b[3] << 24);
}

static uint64_t ar_u64le(arg_reader_t *r)
{
    uint8_t b[8] = {0};
    ar_bytes(r, b, 8);
    uint64_t v = 0;
    for (int i = 7; i >= 0; i--) {
        v = (v << 8) | b[i];
    }
    return v;
}

static float ar_f32le(arg_reader_t *r)
{
    union {
        float f;
        uint32_t u;
    } conv;
    conv.u = ar_u32le(r);
    return conv.f;
}

static double ar_f64le(arg_reader_t *r)
{
    union {
        double d;
        uint64_t u;
    } conv;
    conv.u = ar_u64le(r);
    return conv.d;
}

