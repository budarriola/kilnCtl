// request: none. Reply (docs/PROTOCOL.md section 4): {status, u32 seed,
// u8 snapshot_valid, u32 timescale_x100, u64 sim_time_us}. seed comes from
// sim_engine_get_seed() (always available, even before the first tick).
// timescale_x100/sim_time_us come from the published sim_snapshot_t --
// sim_engine.h exposes no standalone timescale getter, but DESIGN_NOTES.md 4.5's
// snapshot already carries timescale_x100/sim_time_us for exactly this kind
// of read, same source telemetry.c's own TELEMETRY frame uses. Before
// sim_engine's first tick, sim_snapshot_read() returns false: snapshot_valid
// is reported 0 and timescale_x100/sim_time_us are reported 0 rather than
// stale/uninitialized values.
static void handle_sys_get_sim_state(const uint8_t *args, uint8_t args_len, uint8_t *out, uint8_t *out_len,
                                      uint8_t out_cap)
{
    (void)args;
    (void)args_len;

    uint32_t seed = sim_engine_get_seed();
    sim_snapshot_t snap;
    bool snap_ok = sim_snapshot_read(&snap);

    reply_writer_t w;
    rw_init(&w, out, out_cap);
    rw_u8(&w, SIMFW_CMD_STATUS_OK);
    rw_u32le(&w, seed);
    rw_u8(&w, snap_ok ? 1u : 0u);
    rw_u32le(&w, snap_ok ? snap.timescale_x100 : 0u);
    rw_u64le(&w, snap_ok ? snap.sim_time_us : 0u);
    *out_len = w.len;
}

// request: {u32 confirm}. cmd_ids.h's own comment on
// SIMFW_CMD_SYS_REBOOT_BOOTLOADER has the full spec (magic requirement,
// no-reply-on-success convention). safe_reboot_into_bootloader()
// (safe_reboot.h) never returns on success (it jumps into the RP2040's ROM
// USB bootloader after confirming the fixture is in a safe state) -- so
// *out_len is only ever populated on the bad-magic or refusal paths below.
static void handle_sys_reboot_bootloader(const uint8_t *args, uint8_t args_len, uint8_t *out, uint8_t *out_len,
                                          uint8_t out_cap)
{
    arg_reader_t r;
    ar_init(&r, args, args_len);
    uint32_t confirm = ar_u32le(&r);

    reply_writer_t w;
    rw_init(&w, out, out_cap);
    if (r.overflow || confirm != SIMFW_CMD_SYS_REBOOT_BOOTLOADER_MAGIC) {
        rw_u8(&w, SIMFW_CMD_STATUS_ERR_BAD_ARGS);
        *out_len = w.len;
        return;
    }

    // Reached only on the refusal path -- see safe_reboot.h's "refuse,
    // never reboot anyway" policy for why a timed-out safe-state
    // confirmation is reported back rather than rebooting regardless.
    (void)safe_reboot_into_bootloader();
    rw_u8(&w, SIMFW_CMD_STATUS_ERR_BUSY);
    *out_len = w.len;
}

// Named (not anonymous) so s_sys_commands[] below and cmd_group_t's
// `commands` field (also below) refer to the exact same type -- two
// structurally-identical anonymous struct definitions are still distinct,
// incompatible types in C, which an anonymous version of this pair fails
// to compile with (-Wincompatible-pointer-types) the moment one is
// initialized from a pointer to the other.
typedef struct {
    uint8_t cmd_id;
    cmd_handler_fn handler;
} cmd_table_entry_t;

